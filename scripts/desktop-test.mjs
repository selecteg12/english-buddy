import { _electron as electron, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { resolve } from 'node:path';
import { createInterface } from 'node:readline';

const artifacts = resolve('artifacts');
await mkdir(artifacts, { recursive: true });
const report = [];
const environment = { ...process.env };
delete environment.ELECTRON_RUN_AS_NODE;
let app, fixture;
try {
  const data = resolve(artifacts, `desktop-data-${Date.now()}`);
  app = await electron.launch({ args: ['.', `--buddy-data=${data}`], env: environment, timeout: 30000 });
  app.process().stderr.on('data', buffer => { const text = buffer.toString(); if (/startup failed/.test(text)) console.error(text); });
  await expect.poll(() => app.windows().length, { timeout: 20000 }).toBe(3);
  const pages = app.windows();
  const settings = pages.find(page => page.url().includes('view=settings'));
  const popup = pages.find(page => page.url().includes('view=popup'));
  const flag = pages.find(page => page.url().includes('view=flag'));
  const rendererErrors = [];
  for (const page of pages) page.on('pageerror', error => rendererErrors.push(error.message));
  await expect(settings.getByRole('heading', { name: 'A buddy, your way.' })).toBeVisible();
  await settings.getByRole('button', { name: 'Start learning' }).click();
  await expect.poll(() => settings.evaluate(async () => (await window.buddy.getState()).settings.onboardingComplete)).toBe(true);
  await settings.screenshot({ path: resolve(artifacts, 'settings.png') });
  await flag.screenshot({ path: resolve(artifacts, 'flag.png'), omitBackground: true });
  const windowProperties = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().filter(window => !window.webContents.getURL().includes('view=settings')).map(window => ({ alwaysOnTop: window.isAlwaysOnTop(), focusable: window.isFocusable() })));
  expect(windowProperties.every(window => window.alwaysOnTop && !window.focusable)).toBe(true);
  report.push('PASS: launch, onboarding, floating windows stay on top and do not take focus');
  await settings.getByLabel('Look up an English word').fill('consistent');
  await settings.getByRole('button', { name: 'Look up', exact: false }).click();
  await expect.poll(() => popup.evaluate(async () => (await window.buddy.getState()).popup.status), { timeout: 25000 }).toBe('ready');
  const entry = await popup.evaluate(async () => (await window.buddy.getState()).popup.entry);
  expect(entry.definition.length).toBeGreaterThan(0); expect(/[а-яё]/i.test(entry.translation)).toBe(true);
  report.push('PASS: real online definition and Russian translation');
  await popup.screenshot({ path: resolve(artifacts, 'popup-ru.png'), omitBackground: true });
  await popup.getByRole('button', { name: 'EN Definition' }).click();
  await expect(popup.locator('.meaning')).toHaveText(entry.definition);
  await popup.getByRole('button', { name: 'Save word', exact: true }).click();
  await expect(popup.getByRole('button', { name: 'Word saved' })).toBeVisible();
  await popup.screenshot({ path: resolve(artifacts, 'popup-en.png'), omitBackground: true });
  await settings.getByRole('button', { name: /My vocabulary/ }).click();
  await expect(settings.locator('.saved-word')).toHaveCount(1);
  await settings.getByLabel('Search saved words').fill('nothingfound');
  await expect(settings.getByRole('heading', { name: 'No words found.' })).toBeVisible();
  await settings.getByLabel('Search saved words').fill('');
  await settings.screenshot({ path: resolve(artifacts, 'vocabulary.png') });
  report.push('PASS: mode switching, saving, searching vocabulary');
  const rejection = await flag.evaluate(async () => { try { await window.buddy.settings({ popupTimeout: -1 }); return false; } catch { return true; } });
  expect(rejection).toBe(true);
  await popup.getByRole('button', { name: 'Close word' }).click();
  await settings.evaluate(() => window.buddy.settings({ popupTimeout: 0 }));
  const nativeReady = await settings.evaluate(async () => (await window.buddy.getState()).nativeStatus);
  expect(nativeReady).toContain('ready');
  fixture = spawn(resolve('native-bin/SelectionHelper.exe'), ['--fixture'], { windowsHide: false, stdio: 'pipe' });
  const fixtureLines = createInterface({ input: fixture.stdout });
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Native fixture did not open')), 8000);
    fixtureLines.once('line', line => { clearTimeout(timeout); const item = JSON.parse(line); resolve(item); });
    fixture.once('error', reject);
  });
  fixture.stdin.write('auto\n');
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('view=popup')).isVisible()), { timeout: 10000 }).toBe(true);
  await expect.poll(() => popup.evaluate(async () => (await window.buddy.getState()).popup.word), { timeout: 10000 }).toBe('consistent');
  // Closing leaves the word in state, so visibility proves the mouse event reopened it.
  const popupVisible = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('view=popup')).isVisible());
  expect(popupVisible).toBe(true);
  report.push('PASS: automatic selection via a real Windows RichTextBox mouse selection');
  await popup.evaluate(() => window.buddy.closePopup());
  fixture.stdin.write('shortcut\n');
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('view=popup')).isVisible()), { timeout: 10000 }).toBe(true);
  report.push('PASS: Ctrl+Shift+E retrieves Windows selection');
  fixture.stdin.write('password\n');
  await expect.poll(() => popup.evaluate(async () => (await window.buddy.getState()).popup.message), { timeout: 10000 }).toContain('Protected input');
  report.push('PASS: password input ignored');
  fixture.stdin.write('quit\n'); fixtureLines.close();
  await app.close(); app = null;
  app = await electron.launch({ args: ['.', `--buddy-data=${data}`], env: environment });
  await expect.poll(() => app.windows().length).toBe(2);
  const restored = await app.windows().find(page => page.url().includes('view=flag')).evaluate(() => window.buddy.getState());
  expect(restored.settings.mode).toBe('en'); expect(restored.words.map(word => word.word)).toEqual(['consistent']);
  report.push('PASS: mode and vocabulary persist after app restart');
  expect(rendererErrors).toEqual([]);
  report.push('PASS: no renderer JavaScript errors');
} catch (error) {
  report.push(`FAIL: ${error.stack || error.message}`); process.exitCode = 1;
} finally {
  if (fixture && !fixture.killed) fixture.kill();
  if (app) await app.close();
  await writeFile(resolve(artifacts, 'desktop-test.txt'), report.join('\n') + '\n');
  console.log(report.join('\n'));
}
