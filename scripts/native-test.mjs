import { spawn } from 'node:child_process';
import { resolve } from 'node:path';
import { createInterface } from 'node:readline';
const helperPath = resolve('native-bin/SelectionHelper.exe');
const helper = spawn(helperPath, [String(process.pid), '--diagnostic'], { windowsHide: true });
const fixture = spawn(helperPath, ['--fixture'], { windowsHide: false });
const lines = createInterface({ input: helper.stdout });
lines.on('line', line => console.log(line));
helper.stderr.on('data', data => console.error(data.toString()));
const fixtureLines = createInterface({ input: fixture.stdout });
fixtureLines.on('line', line => console.log(`fixture: ${line}`));
await new Promise(resolvePromise => fixtureLines.once('line', resolvePromise));
helper.stdin.write('{"type":"enabled","value":true}\n');
fixture.stdin.write('auto\n');
await new Promise(resolvePromise => setTimeout(resolvePromise, 3000));
helper.stdin.write('{"type":"capture","id":"test"}\n');
await new Promise(resolvePromise => setTimeout(resolvePromise, 3000));
helper.stdin.write('{"type":"quit"}\n'); fixture.stdin.write('quit\n');
helper.kill(); fixture.kill(); lines.close();
